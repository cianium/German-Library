import fs from 'node:fs';
import path from 'node:path';

const root=path.resolve(import.meta.dirname,'..');
const url=(process.env.SUPABASE_URL||'').trim();
const key=(process.env.SUPABASE_PUBLISHABLE_KEY||'').trim();
const social=(raw,hosts,name)=>{const value=String(raw||'').trim();if(!value)return '';try{const u=new URL(value);if(u.protocol!=='https:'||!hosts.includes(u.hostname.toLowerCase())||u.pathname==='/'||!u.pathname)throw Error();return u.href}catch{console.error(`${name} must be an official HTTPS profile URL.`);process.exit(1)}};
const instagramUrl=social(process.env.INSTAGRAM_URL||'https://instagram.com/lexipfad',['instagram.com','www.instagram.com'],'INSTAGRAM_URL');
const telegramUrl=social(process.env.TELEGRAM_URL||'https://t.me/lexipfad',['t.me','www.t.me','telegram.me'],'TELEGRAM_URL');
if((url&&!key)||(!url&&key)){
  console.error('SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY must be provided together.');
  process.exit(1);
}
if(key && !key.startsWith('sb_publishable_')){
  console.error('Only a modern sb_publishable_ public key is accepted. Secret/service-role keys must never reach frontend config.');
  process.exit(1);
}
if(url && !/^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/i.test(url)){
  console.error('SUPABASE_URL must be an HTTPS Supabase project URL.');process.exit(1);
}
const js=`/* Generated by scripts/configure.mjs. Never place a Supabase secret/service_role key here. */\nwindow.GL_CONFIG={\n  allowDemoAdmin:false,\n  supabaseUrl:${JSON.stringify(url)},\n  supabasePublishableKey:${JSON.stringify(key)},\n  supabaseAnonKey:"",\n  instagramUrl:${JSON.stringify(instagramUrl)},\n  telegramUrl:${JSON.stringify(telegramUrl)},\n  syncDebounceMs:350,\n  maxUploadBytes:262144000\n};\n`;
fs.writeFileSync(path.join(root,'assets/runtime-config.js'),js);
console.log(url ? 'Configured Supabase production client.' : 'Generated local/demo config (Supabase disabled).');
