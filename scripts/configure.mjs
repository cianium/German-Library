import fs from 'node:fs';
import path from 'node:path';

const root=path.resolve(import.meta.dirname,'..');
const url=(process.env.SUPABASE_URL||'').trim();
const key=(process.env.SUPABASE_PUBLISHABLE_KEY||'').trim();
if((url&&!key)||(!url&&key)){
  console.error('SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY must be provided together.');
  process.exit(1);
}
if(key && !key.startsWith('sb_publishable_')){
  console.error('Only a modern sb_publishable_ public key is accepted. Secret/service-role keys must never reach frontend config.');
  process.exit(1);
}
if(url && !/^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/i.test(url)){
  console.error('SUPABASE_URL must be an HTTPS Supabase project URL.');process.exit(1);
}
const js=`/* Generated by scripts/configure.mjs. Never place a Supabase secret/service_role key here. */\nwindow.GL_CONFIG={\n  allowDemoAdmin:false,\n  supabaseUrl:${JSON.stringify(url)},\n  supabasePublishableKey:${JSON.stringify(key)},\n  supabaseAnonKey:"",\n  syncDebounceMs:350,\n  maxUploadBytes:262144000\n};\n`;
fs.writeFileSync(path.join(root,'assets/runtime-config.js'),js);
console.log(url ? 'Configured Supabase production client.' : 'Generated local/demo config (Supabase disabled).');
